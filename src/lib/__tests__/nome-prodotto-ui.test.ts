import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

/**
 * INVARIANTE: nei testi che l'utente legge il prodotto si chiama DA-IPAM.
 *
 * UI-23 (piano di miglioramento, tappa 1; decisione di Riccardo del
 * 2026-10-12). Fino a v0.3.266 barra laterale, setup, login, scelta del
 * cliente, titolo della scheda del browser e alcuni messaggi d'errore dicevano
 * «DA-INVENT», mentre documenti, Launchpad e indirizzi dicevano DA-IPAM: due
 * nomi per la stessa cosa, e chi legge non sa se sono due prodotti.
 *
 * «DA-INVENT» resta lecito solo dove è un identificatore tecnico, che cambiare
 * romperebbe qualcosa fuori da questo repo (elenco `TECNICI` sotto) e nei
 * commenti. Gli identificatori in minuscolo (servizio `da-invent`,
 * `/opt/da-invent`, `~/.da-invent-venv`) e le variabili `DA_INVENT_*` non
 * c'entrano: non contengono «DA-INVENT» maiuscolo col trattino.
 */

const SRC = path.join(process.cwd(), "src");

/** Righe in cui «DA-INVENT» è un identificatore tecnico, non un testo per l'utente. */
const TECNICI: RegExp[] = [
  /User-Agent/, // sonde HTTP e SSDP: i dispositivi registrano questo nome nei loro log
  /X-Requested-By/, // header che l'API di Graylog pretende
  /DA-INVENT-KRB5-DNS-SRV/, // marcatore che riconosce i krb5.conf generati da noi
  /Auto-generated by DA-INVENT/, // intestazione dei krb5.conf generati
  /'DA-INVENT auto'/, // descrizione del token creato su LibreNMS
];

function isComment(line: string): boolean {
  const t = line.trim();
  return (
    t.startsWith("//") || t.startsWith("*") || t.startsWith("/*") || t.startsWith("{/*") || t.startsWith("#")
  );
}

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".next" || entry.name === "__tests__") continue;
      out.push(...sourceFiles(full));
    } else if (/\.(tsx?|py)$/.test(entry.name) && !entry.name.endsWith(".test.ts")) {
      out.push(full);
    }
  }
  return out;
}

test("nei testi visibili il prodotto si chiama DA-IPAM, non DA-INVENT (UI-23)", () => {
  const offenders: string[] = [];

  for (const file of sourceFiles(SRC)) {
    const lines = fs.readFileSync(file, "utf8").split("\n");
    lines.forEach((line, i) => {
      if (!line.includes("DA-INVENT")) return;
      if (isComment(line) || TECNICI.some((re) => re.test(line))) return;
      offenders.push(`${path.relative(process.cwd(), file)}:${i + 1}: ${line.trim()}`);
    });
  }

  assert.deepEqual(
    offenders,
    [],
    `Testi per l'utente con il nome vecchio (usare DA-IPAM; se è un identificatore tecnico, aggiungerlo a TECNICI col perché):\n${offenders.join("\n")}`,
  );
});
